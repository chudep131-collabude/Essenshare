// Helper to deep merge or fallback to English keys
function createLocale(translations) {
  function merge(base, override) {
    const res = { ...base };
    for (const key of Object.keys(override || {})) {
      if (typeof override[key] === 'object' && override[key] !== null && !Array.isArray(override[key])) {
        res[key] = merge(base[key] || {}, override[key]);
      } else {
        res[key] = override[key];
      }
    }
    return res;
  }
  return merge(en, translations);
}

